"""Shared pytest fixtures for the databricks-vision app.

The FastAPI app is exercised through `TestClient` WITHOUT running its lifespan: lifespan would
build a real `WorkspaceClient`, open a Lakebase pool and configure MLflow. Instead each test
installs exactly the `app.state` it needs (config, a fake WorkspaceClient, and optionally a real
Postgres pool from tests/integration/conftest.py). Every app dependency (`Dependencies.Client`,
`.UserClient`, `.DB`, `.Config`) resolves from `app.state`, so no dependency overrides are needed.
"""
from __future__ import annotations

import tomllib
from collections.abc import Iterator
from pathlib import Path

import pytest

APP_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = APP_DIR.parent
PACKAGE_DIR = APP_DIR / "src" / "databricks_vision"


def _ensure_apx_metadata() -> None:
    """`_metadata.py` is generated by `apx build` and gitignored; the backend imports it.
    Write the same four constants from [tool.apx.metadata] so tests run from a clean checkout."""
    target = PACKAGE_DIR / "_metadata.py"
    if target.exists():
        return
    meta = tomllib.loads((APP_DIR / "pyproject.toml").read_text())["tool"]["apx"]["metadata"]
    target.write_text(
        f'app_name = "{meta["app-name"]}"\n'
        f'app_module = "{meta["app-module"]}"\n'
        f'app_slug = "{meta["app-slug"]}"\n'
        f'api_prefix = "{meta["api-prefix"]}"\n'
    )


_ensure_apx_metadata()

from fastapi.testclient import TestClient  # noqa: E402  (must follow _metadata generation)

from tests.fakes import FakeWorkspaceClient  # noqa: E402


@pytest.fixture
def fake_ws() -> FakeWorkspaceClient:
    return FakeWorkspaceClient()


@pytest.fixture
def app_config():
    from databricks_vision.backend.core._config import AppConfig

    # eval_experiment="" keeps MLflow out of every code path that checks it.
    return AppConfig(catalog="test_catalog", schema_name="test_schema", eval_experiment="")


@pytest.fixture
def app(app_config, fake_ws):
    """The real app object with a test-controlled `app.state` (no pool, no evaluator)."""
    from databricks_vision.backend.app import app as fastapi_app

    fastapi_app.state.config = app_config
    fastapi_app.state.workspace_client = fake_ws
    fastapi_app.state.db_pool = None
    fastapi_app.state.image_evaluator = None
    yield fastapi_app
    fastapi_app.dependency_overrides.clear()


@pytest.fixture
def client(app) -> Iterator[TestClient]:
    # Deliberately not `with TestClient(app)`: that would run the production lifespan.
    yield TestClient(app)
